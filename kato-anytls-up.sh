#!/usr/bin/env bash

# Kato AnyTLS —— 直接连一个 AnyTLS 上游节点。
# 上游参数全部从仓库根目录 .env 读取（gitignored，模板 .env.example），
# 也可直接以环境变量传入（环境变量优先于 .env）：
#   ANYTLS_SERVER / ANYTLS_PORT / ANYTLS_PASSWORD   必填
#   ANYTLS_SNI                                      可选，默认同 ANYTLS_SERVER
#   ANYTLS_SKIP_CERT_VERIFY                         可选，默认 false
#   ANYTLS_NAME                                     可选，节点显示名
#
# 本地代理:
#   http/mixed: 127.0.0.1:7897
#
# 用法：
#   ./kato-anytls-up.sh

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

export CLASH_HOME="${CLASH_HOME:-$HOME/.local/share/clash}"

# 读 .env（不覆盖已在环境里的同名变量）
if [ -f "$HERE/.env" ]; then
    _pre="$(declare -p ANYTLS_SERVER ANYTLS_PORT ANYTLS_PASSWORD ANYTLS_SNI ANYTLS_SKIP_CERT_VERIFY ANYTLS_NAME 2>/dev/null || true)"
    set -a; . "$HERE/.env"; set +a
    eval "$_pre"
fi

_need_env="请在 $HERE/.env 里填好（模板见 .env.example）"
SERVER="${ANYTLS_SERVER:?未设置。$_need_env}"
PORT="${ANYTLS_PORT:?未设置。$_need_env}"
PASSWORD="${ANYTLS_PASSWORD:?未设置。$_need_env}"

# 默认使用服务器域名作为 SNI；服务商另给了 SNI 就设 ANYTLS_SNI。
SNI="${ANYTLS_SNI:-$SERVER}"

# 默认校验证书，更安全；服务端是自签名证书时设 ANYTLS_SKIP_CERT_VERIFY=true。
SKIP_CERT_VERIFY="${ANYTLS_SKIP_CERT_VERIFY:-false}"

NAME="${ANYTLS_NAME:-anytls}"

CONFIG="$CLASH_HOME/config.yaml"

echo "[*] CLASH_HOME = $CLASH_HOME"
echo "[*] SNI = $SNI"
echo "[*] Local proxy = 127.0.0.1:7897"

mkdir -p "$CLASH_HOME"

# ------------------------------------------------------------
# 安装 / 校验 mihomo
# ------------------------------------------------------------

if [ -x "$HERE/clash.sh" ]; then
    echo "[*] 安装/校验 mihomo 内核 + GeoIP ..."
    "$HERE/clash.sh" install
else
    echo "[!] 找不到 $HERE/clash.sh"
    echo "[!] 请把本脚本放在 clash.sh 所在目录。"
    exit 1
fi

# ------------------------------------------------------------
# 备份旧配置
# ------------------------------------------------------------

if [ -f "$CONFIG" ]; then
    BACKUP="$CONFIG.bak.$(date +%Y%m%d-%H%M%S)"
    echo "[*] 备份旧配置到：$BACKUP"
    cp "$CONFIG" "$BACKUP"
fi

# ------------------------------------------------------------
# 写入 Mihomo AnyTLS 配置
# ------------------------------------------------------------

echo "[*] 写入 AnyTLS 配置 ..."

( umask 077; cat > "$CONFIG" <<EOF
# ============================================================
# Kato AnyTLS
# Generated by kato-anytls-up.sh
# ============================================================

mixed-port: 7897

# 只允许本机访问 7897
allow-lan: false
bind-address: 127.0.0.1

mode: rule
log-level: info

proxies:
  - name: "${NAME}"
    type: anytls
    server: "${SERVER}"
    port: ${PORT}
    password: "${PASSWORD}"

    # uTLS 指纹
    client-fingerprint: chrome

    # AnyTLS 支持 UDP
    udp: true

    # ALPN
    alpn: [h2, http/1.1]

    # TLS
    sni: "${SNI}"
    skip-cert-verify: ${SKIP_CERT_VERIFY}

    # AnyTLS session 参数
    idle-session-check-interval: 30
    idle-session-timeout: 30
    min-idle-session: 0

proxy-groups:
  - name: "PROXY"
    type: select
    proxies:
      - "${NAME}"

rules:
  - MATCH,PROXY
EOF
)

chmod 600 "$CONFIG"

# ------------------------------------------------------------
# 重启 Mihomo
# ------------------------------------------------------------

echo "[*] 重启 mihomo ..."

"$HERE/clash.sh" restart

echo
echo "[*] Mihomo 状态："
"$HERE/clash.sh" status || true

echo
echo "============================================================"
echo "Kato AnyTLS 已启动"
echo
echo "本地代理："
echo "  http://127.0.0.1:7897"
echo
echo "当前 shell 开代理："
echo
echo "  export http_proxy=http://127.0.0.1:7897"
echo "  export https_proxy=http://127.0.0.1:7897"
echo "  export HTTP_PROXY=http://127.0.0.1:7897"
echo "  export HTTPS_PROXY=http://127.0.0.1:7897"
echo
echo "验证："
echo
echo "  curl -x http://127.0.0.1:7897 https://www.cloudflare.com/cdn-cgi/trace"
echo
echo "测试 npm："
echo
echo "  curl -I -x http://127.0.0.1:7897 https://registry.npmjs.org/@openai%2fcodex"
echo "============================================================"
